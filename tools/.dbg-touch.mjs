await p.goto(base+'/?explorer-preview=page&page=vault',{waitUntil:'domcontentloaded'});
await p.waitForSelector('.explorer-shell'); await p.waitForTimeout(1500);
await p.evaluate(async()=>{const u=performance.getEntriesByType('resource').map(r=>r.name).find(x=>new URL(x).pathname.endsWith('/src/state/vault.ts'));const m=await import(u);m.addToVault({type:'text',title:'测试',text:'内容'});});
await p.evaluate(()=>localStorage.setItem('onethu.cards.v1', JSON.stringify({v:1,personal:{name:'碰一碰测试',avatar:'',website:'',social:'',phone:'13800000000',bio:'一句话',updatedAt:Date.now()},orgs:[],contacts:[]})));
