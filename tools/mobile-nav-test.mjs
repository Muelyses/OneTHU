/** 手机返回键根级退出：前端命令、Kotlin activity finish、ACL 权限三方一致。 */
import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
let n = 0;
const ok = (c, m) => { assert.ok(c, m); n++; console.log('✓ ' + m); };
const nav = readFileSync(new URL('../apps/desktop/src/state/navStack.ts', import.meta.url), 'utf8');
const kt = readFileSync(new URL('../apps/desktop/src-tauri/plugins/onethu-mobile/android/src/main/java/app/onethu/mobile/OnethuMobilePlugin.kt', import.meta.url), 'utf8');
const perm = readFileSync(new URL('../apps/desktop/src-tauri/plugins/onethu-mobile/permissions/default.toml', import.meta.url), 'utf8');
const cmd = readFileSync(new URL('../apps/desktop/src-tauri/plugins/onethu-mobile/permissions/autogenerated/commands/mobile_exit.toml', import.meta.url), 'utf8');
ok(/plugin:onethu-mobile\|mobile_exit/.test(nav), '前端根级返回调用 mobile_exit 插件命令');
ok(/fun mobileExit\(invoke: Invoke\)/.test(kt) && /finishAffinity\(\)/.test(kt), 'Kotlin 命令 finish 当前 Activity');
ok(/allow-mobile-exit/.test(perm), '插件 default 权限包含 allow-mobile-exit');
ok(/commands\.allow = \["mobile_exit"\]/.test(cmd), '命令 permission 文件声明 mobile_exit');
console.log(n + ' mobile navigation assertions passed');
