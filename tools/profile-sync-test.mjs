import assert from 'node:assert/strict';
import { captureProfile, flattenProfile, materializeProfile, mergeProfile, newProfileState, parseProfileState, profileConflicts, profileConflictPaths, resolveProfileConflict, mergedProfileConflict } from '../apps/desktop/src/state/profileSyncCore.ts';
const me = 'me@example.test';
const card = (name='', updatedAt=0) => ({name,avatar:'',website:'',social:'',phone:'',bio:'',updatedAt});
const docs = (name='',contacts=[],orgs=[]) => flattenProfile({v:1,personal:card(name,name?100:0),contacts,orgs:[]},{v:1,orgs});
const contact = id => ({id,kind:'personal',name:id,note:'',card:card(id,100),addedAt:100});
const fresh = d => newProfileState(me, 'device-'+d);
let a=captureProfile(fresh('mac'),docs('Mac',[contact('friend')]));
let b=captureProfile(fresh('win'),docs());
b=mergeProfile(b,a);
assert.equal(materializeProfile(b,card()).cards.personal.name,'Mac','empty device cannot replace a real card');
assert.equal(materializeProfile(b,card()).cards.contacts.length,1);
assert.deepEqual(mergeProfile(a,b).records,mergeProfile(b,a).records,'merge converges');
const original=docs('Mac',[contact('friend')]);
a=captureProfile(a,docs('Mac'),original);
assert.equal(materializeProfile(mergeProfile(b,a),card()).cards.contacts.length,0,'delete beats an offline stale replica');
assert.equal(materializeProfile(mergeProfile(a,b),card()).cards.contacts.length,0,'tombstone prevents resurrection');
let c=captureProfile(fresh('phone'),docs('',[contact('second')]));
const combined=materializeProfile(mergeProfile(a,c),card());
assert.deepEqual(combined.cards.contacts.map(c=>c.id),['second'],'independent additions survive deletion of another friend');
const left=mergeProfile(mergeProfile(a,b),c),right=mergeProfile(a,mergeProfile(b,c));
assert.deepEqual(left.records,right.records,'merge is associative');
assert.deepEqual(mergeProfile(a,a).records,a.records,'merge is idempotent');
assert.throws(()=>mergeProfile(a,newProfileState('other@example.test','device-other')),/account mismatch/);
assert.throws(()=>parseProfileState(JSON.stringify(a),'other@example.test'),/Invalid/);
assert.deepEqual(parseProfileState(JSON.stringify(a),me).records,a.records);
const invalid=JSON.parse(JSON.stringify(a));invalid.records.personal.value={name:'incomplete'};
assert.throws(()=>parseProfileState(JSON.stringify(invalid),me),/Invalid profile record/);
const noDevice=JSON.parse(JSON.stringify(a));delete noDevice.device;
assert.throws(()=>parseProfileState(JSON.stringify(noDevice),me),/Invalid/);
const org={id:'org1',name:'Study',brief:'',joinUrl:'',cloudRepoId:'',cloudPath:'',members:[],createdAt:100,updatedAt:100};
const withOrg=captureProfile(fresh('orgs'),docs('',[],[org]));
assert.equal(materializeProfile(mergeProfile(a,withOrg),card()).orgs.orgs[0].id,'org1');
const removed=captureProfile(withOrg,docs(),docs('',[],[org]));
assert.equal(materializeProfile(mergeProfile(withOrg,removed),card()).orgs.orgs.length,0);
const baseline=captureProfile(fresh('base'),docs('Original'));
const fork=(device,patch)=>{const s=mergeProfile(fresh(device),baseline);const before=docs('Original'),after=structuredClone(before);after.personal={...after.personal,...patch};return captureProfile(s,after,before)};
const bio=fork('mac-edit',{bio:'Mac bio'}),web=fork('win-edit',{website:'https://example.test'});
const independent=profileConflicts(bio,web)[0];assert.ok(independent);
assert.deepEqual(profileConflictPaths(independent),[],'independent card fields do not prompt');
const merged=resolveProfileConflict(bio,independent,'merge');
assert.equal(merged.records.personal.value.bio,'Mac bio');assert.equal(merged.records.personal.value.website,'https://example.test');
assert.equal(profileConflicts(merged,web).length,0,'an acknowledged merge is not a fresh conflict');
const olderFork=captureProfile(bio,{...docs('Original'),personal:{...bio.records.personal.value,phone:'new local phone'}},{...docs('Original'),personal:bio.records.personal.value});
const mergedOnWindows=resolveProfileConflict(web,profileConflicts(web,bio)[0],'merge');
const continued=profileConflicts(olderFork,mergedOnWindows)[0];
assert.deepEqual(profileConflictPaths(continued),[],'an offline branch uses its acknowledged ancestor after another device merged');
assert.equal(mergedProfileConflict(continued).website,'https://example.test');
assert.equal(mergedProfileConflict(continued).phone,'new local phone');
const namedA=fork('mac-name',{name:'Local name'}),namedB=fork('win-name',{name:'Remote name'});
const conflict=profileConflicts(namedA,namedB)[0];assert.deepEqual(profileConflictPaths(conflict),['personal.name']);
assert.equal(resolveProfileConflict(namedA,conflict,'local').records.personal.value.name,'Local name');
assert.equal(resolveProfileConflict(namedA,conflict,'remote').records.personal.value.name,'Remote name');
assert.equal(mergedProfileConflict(conflict).name,'Local name','explicit merge preview preserves local same-field edits');
const mixedA=fork('mac-mixed',{name:'Local name',phone:'local phone'}),mixedB=fork('win-mixed',{name:'Remote name',website:'https://remote.example.test'});
const mixed=profileConflicts(mixedA,mixedB)[0];
const chosen=resolveProfileConflict(mixedA,mixed,'remote').records.personal.value;
assert.equal(chosen.name,'Remote name');assert.equal(chosen.phone,'local phone');assert.equal(chosen.website,'https://remote.example.test','choosing another version does not discard compatible edits');
const orgBase=captureProfile(fresh('org-base'),docs('',[],[{...org,members:[{id:'m1',name:'Sam',email:'sam@example.test',role:'member',joinedAt:100}]}]));
const orgBefore=flattenProfile(materializeProfile(orgBase,card()).cards,materializeProfile(orgBase,card()).orgs);
const roleFork=(device,role)=>{const s=mergeProfile(fresh(device),orgBase),current=structuredClone(orgBefore);current['org:org1'].members[0].role=role;return captureProfile(s,current,orgBefore)};
assert.deepEqual(profileConflictPaths(profileConflicts(roleFork('org-mac','owner'),roleFork('org-win','guest'))[0]),['org:org1.members.m1.role'],'incompatible organization roles require a human choice');
const deletion=captureProfile(baseline,{},docs('Original'));
assert.ok(profileConflictPaths(profileConflicts(deletion,namedB)[0]).length,'concurrent deletion versus modification prompts');
console.log('Profile merge: blank-device protection, convergence, tombstones, account isolation, automatic field merging and real-conflict local/remote/merge choices passed.');
